#!/usr/bin/env sh
set -eu

CLAUDE_BIN=${CLAUDE_CODE_BIN:-claude}
CLAUDE_CODE_WORKSPACE=${CLAUDE_CODE_WORKSPACE:-$(pwd)}
CLAUDE_CODE_WORKSPACE_ID=${CLAUDE_CODE_WORKSPACE_ID:-ws_$(printf '%s' "$CLAUDE_CODE_WORKSPACE" | cksum | awk '{print $1}')}
CLAUDE_CODE_INSTANCE_ID=${CLAUDE_CODE_INSTANCE_ID:-$(hostname)}
CLAUDE_CODE_RUN_ID=${CLAUDE_CODE_RUN_ID:-ccrun_${CLAUDE_CODE_WORKSPACE_ID}_$$_$(date +%s)}
ANTHROPIC_CUSTOM_HEADERS="X-Agent-Name: claude-code
X-Agent-Run-Id: ${CLAUDE_CODE_RUN_ID}
X-Agent-Workspace-Id: ${CLAUDE_CODE_WORKSPACE_ID}
X-Agent-Workspace: ${CLAUDE_CODE_WORKSPACE}
X-Instance-Id: ${CLAUDE_CODE_INSTANCE_ID}"

export CLAUDE_CODE_WORKSPACE CLAUDE_CODE_WORKSPACE_ID CLAUDE_CODE_INSTANCE_ID CLAUDE_CODE_RUN_ID ANTHROPIC_CUSTOM_HEADERS

exec "$CLAUDE_BIN" "$@"
